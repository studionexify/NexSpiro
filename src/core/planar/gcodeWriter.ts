// G-code writer of the planar slicer: Bambu/Orca-compatible header, annotations (;TYPE: ;WIDTH: ;HEIGHT:), relative E, cooling, labels.
import { FEATURE_GCODE_TYPE } from "./types.ts";
import type { PlanarPlan, PlanarJob, GcodeResult } from "./types.ts";
import { planMoves, slowed } from "./motion.ts";
import type { PlannedMove } from "./motion.ts";
import { fillTemplate } from "../presets.ts";
import { formatDuration } from "../gcode.ts";
import type { Thumbnail } from "../gcode.ts";

export type PlanarGcodeOptions = {
  offset?: [number, number]; thumbnails?: Thumbnail[];
  presetNames?: { machine: string; filament: string; process: string };
  plateName?: string; inputName?: string;
};

const f = (v: number, d = 3) => { const s = v.toFixed(d).replace(/\.?0+$/, "") || "0"; return s === "-0" ? "0" : s; };

function thumbnailBlock(t: Thumbnail): string[] {
  const out = [`; thumbnail begin ${t.width}x${t.height} ${t.pngBase64.length}`];
  for (let i = 0; i < t.pngBase64.length; i += 78) out.push(`; ${t.pngBase64.slice(i, i + 78)}`);
  out.push("; thumbnail end", ";");
  return out;
}
const safeName = (s: string, i: number) => `${s.replace(/[^A-Za-z0-9_.-]+/g, "_") || "object"}_id_${i}`;

export function writePlanarGcode(plan: PlanarPlan, job: PlanarJob, opts: PlanarGcodeOptions = {}): GcodeResult {
  const mp = planMoves(plan, job);
  const { ctx } = mp;
  const { M, F, P } = ctx;
  const [ox, oy] = opts.offset ?? [0, 0];
  const flavor = M.flavor, klipper = flavor === "klipper";
  const nLayers = plan.layers.length;
  const comments = ctx.bool("gcode_comments"), lineNo = ctx.bool("gcode_add_line_number"), label = ctx.bool("gcode_label_objects");
  const byObject = plan.sequence === "object";
  const maxZ = mp.maxZ;
  const names = plan.objectNames.length ? plan.objectNames : job.objects.map((o) => o.name);

  const out: string[] = [
    "; HEADER_BLOCK_START",
    "; generated by NexSpiro (Studio Nexify)",
    `; model printing time: ${formatDuration(mp.timeS)}; total estimated time: ${formatDuration(mp.timeS)}`,
    `; estimated printing time (normal mode) = ${formatDuration(mp.timeS)}`,
    `; total layer number: ${nLayers}`,
    `; filament used [mm] = ${mp.filamentMm.toFixed(2)}`,
    `; filament used [cm3] = ${mp.filamentCm3.toFixed(2)}`,
    `; filament used [g] = ${mp.grams.toFixed(2)}`,
    `; total filament cost = ${mp.cost.toFixed(2)}`,
    `; filament used [m] = ${(mp.filamentMm / 1000).toFixed(3)}`,
    `; max_z_height: ${f(maxZ, 2)}`,
    `; objects: ${Math.max(job.objects.length, plan.bounds.length)} (${byObject ? "by object" : "by layer"})`,
    "; HEADER_BLOCK_END", ";",
  ];
  if (opts.thumbnails?.length) {
    out.push("; THUMBNAIL_BLOCK_START");
    for (const t of opts.thumbnails) out.push(...thumbnailBlock(t));
    out.push("; THUMBNAIL_BLOCK_END", ";");
  }
  if (opts.presetNames) out.push(`; printer_settings_id = ${opts.presetNames.machine}`, `; filament_settings_id = ${opts.presetNames.filament}`, `; print_settings_id = ${opts.presetNames.process}`);
  if (opts.plateName) out.push(`; plate_name = ${opts.plateName}`);
  if (opts.inputName) out.push(`; input_name = ${opts.inputName}`);
  out.push(`; flavor = ${flavor}`, `; print_sequence = ${byObject ? "by object" : "by layer"}`, ";", "; EXECUTABLE_BLOCK_START");

  const labelId = (o: number) => safeName(names[o] ?? `object_${o}`, o);
  if (label && klipper) {
    plan.bounds.forEach((b, i) => {
      const [x0, y0, x1, y1] = [b[0] + ox, b[1] + oy, b[2] + ox, b[3] + oy];
      out.push(`EXCLUDE_OBJECT_DEFINE NAME=${labelId(i)} CENTER=${f((x0 + x1) / 2)},${f((y0 + y1) / 2)} POLYGON=[[${f(x0)},${f(y0)}],[${f(x1)},${f(y0)}],[${f(x1)},${f(y1)}],[${f(x0)},${f(y1)}]]`);
    });
  }
  const vars: Record<string, string | number> = {
    bed_temperature_initial_layer: F.bedTempFirst, bed_temperature: F.bedTemp,
    nozzle_temperature_initial_layer: F.nozzleTempFirst, nozzle_temperature: F.nozzleTemp,
    bed_x: M.bed[0], bed_y: M.bed[1], travel_feed: Math.round(ctx.travelSpeed * 60), total_layer_count: nLayers,
    layer_height: P.layerHeight, first_layer_height: P.firstLayerHeight, max_z_height: f(maxZ, 2), nozzle_diameter: M.nozzle,
  };
  out.push(...fillTemplate(M.startGcode, vars).split("\n"));
  out.push("M83", "G92 E0");
  if (ctx.pa > 0) out.push(klipper ? `SET_PRESSURE_ADVANCE ADVANCE=${f(ctx.pa, 4)}` : `M900 K${f(ctx.pa, 4)}`);

  // ---- state
  let curF = -1, curZ = NaN, curFan = -1, curAccel = -1, curJerk = -1, curType = -1, curWidth = -1, curHeight = -1, curAux = false;
  let eExact = 0, eEmitted = 0, bedSwitched = false;
  const eDelta = (e: number) => { eExact += e; const d = Math.round((eExact - eEmitted) * 1e5) / 1e5; eEmitted += d; return d; };
  const fanS = (pct: number) => Math.round((pct / 100) * 255);
  const setFan = (pct: number) => { const s = fanS(pct); if (s !== curFan) { curFan = s; out.push(`M106 S${s}`); } };
  const setAccel = (m: PlannedMove) => {
    const a = Math.round(m.accel);
    if (klipper) { if (a !== curAccel) { curAccel = a; out.push(`SET_VELOCITY_LIMIT ACCEL=${a}`); } }
    else if (m.kind === "extrude" || m.kind === "wipe") {
      if (a !== curAccel) { curAccel = a; out.push(`M204 P${a} T${Math.round(ctx.travelAccel)}`); }
    }
  };
  const setJerk = (m: PlannedMove) => {
    const j = m.jerk;
    if (!(j > 0) || j === curJerk) return;
    curJerk = j;
    out.push(klipper ? `SET_VELOCITY_LIMIT SQUARE_CORNER_VELOCITY=${f(j)}` : `M205 X${f(j)} Y${f(j)}`);
  };
  const feed = (v: number) => { const F60 = Math.round(v * 60); if (F60 === curF) return ""; curF = F60; return ` F${F60}`; };
  const note = (s: string | undefined) => (comments && s ? ` ; ${s}` : "");

  let cum = 0;
  const total = Math.max(mp.timeS, 1e-9);
  for (const lm of mp.layers) {
    const { layer, ordinal } = lm;
    out.push(";LAYER_CHANGE", `;Z:${f(layer.z)}`, `;HEIGHT:${f(layer.height)}`);
    out.push(...fillTemplate(M.layerChangeGcode, { ...vars, layer_num: lm.pos + 1, layer_z: f(layer.z) }).split("\n"));
    if (lm.objSwitch && ordinal === 0) out.push(`M104 S${F.nozzleTempFirst}`);
    if (ordinal === 1) { out.push(`M104 S${F.nozzleTemp}`); if (!bedSwitched) { out.push(`M140 S${F.bedTemp}`); bedSwitched = true; } }
    if (flavor !== "klipper") out.push(`M73 P${Math.min(100, Math.round((cum / total) * 100))} R${Math.max(0, Math.ceil((mp.timeS - cum) / 60))}`);
    cum += lm.time;
    setFan(lm.fanPct);
    if (!curAux && F.auxFanSpeed > 0 && flavor !== "klipper" && ordinal >= F.fanOffFirstLayers) { curAux = true; out.push(`M106 P2 S${fanS(F.auxFanSpeed)}`); }
    curType = -1; curHeight = layer.height;
    for (const m of lm.moves) {
      switch (m.kind) {
        case "mark": {
          if (!label || m.label === undefined) break;
          if (klipper) out.push(`EXCLUDE_OBJECT_${m.mark === "start" ? "START" : "END"} NAME=${labelId(m.label)}`);
          else out.push(`; ${m.mark === "start" ? "start" : "stop"} printing object, unique label id: ${m.label}`);
          if (m.mark === "start") curType = -1;
          break;
        }
        case "retract": case "deretract": {
          out.push(`G1 E${f(eDelta(m.e), 5)}${feed(m.speed)}${note(m.note)}`);
          break;
        }
        case "travel": {
          if (m.len === 0 && m.e === 0 && !Number.isNaN(curZ)) break;
          setAccel(m); setJerk(m);
          const dxy = Math.hypot(m.x - m.x0, m.y - m.y0) > 1e-9 || Number.isNaN(curZ);
          const zc = Number.isNaN(curZ) || Math.abs(m.z - curZ) > 1e-9;
          let s = dxy ? "G0" : "G1";
          if (dxy) s += ` X${f(m.x + ox)} Y${f(m.y + oy)}`;
          if (zc) s += ` Z${f(m.z)}`;
          curZ = m.z;
          out.push(s + feed(m.speed) + note(m.note));
          break;
        }
        case "wipe": {
          setAccel(m);
          out.push(`G1 X${f(m.x + ox)} Y${f(m.y + oy)}${Math.abs(m.z - curZ) > 1e-9 ? ` Z${f(m.z)}` : ""} E${f(eDelta(m.e), 5)}${feed(m.speed)}${note(m.note)}`);
          curZ = m.z;
          break;
        }
        case "extrude": {
          if (m.feature !== curType) { curType = m.feature; out.push(`;TYPE:${FEATURE_GCODE_TYPE[m.feature] ?? "Custom"}`); curWidth = -1; }
          if (Math.abs(m.height - curHeight) > 1e-6) { curHeight = m.height; out.push(`;HEIGHT:${f(curHeight)}`); }
          if (Math.abs(m.width - curWidth) > 1e-6) { curWidth = m.width; out.push(`;WIDTH:${f(curWidth)}`); }
          if (m.fan !== undefined) setFan(m.fanAtLeast ? Math.max(lm.fanPct, m.fan) : m.fan); else setFan(lm.fanPct);
          setAccel(m); setJerk(m);
          const v = slowed(m.speed, lm.factor, F.minSpeed);
          const zc = Math.abs(m.z - curZ) > 1e-9;
          out.push(`G1 X${f(m.x + ox)} Y${f(m.y + oy)}${zc ? ` Z${f(m.z)}` : ""} E${f(eDelta(m.e), 5)}${feed(v)}${m.pathStart ? note(FEATURE_GCODE_TYPE[m.feature]) : ""}`);
          curZ = m.z;
          break;
        }
      }
    }
  }
  out.push(...fillTemplate(M.endGcode, vars).split("\n"), "; EXECUTABLE_BLOCK_END", "");
  let text: string;
  if (lineNo) {
    let n = 0;
    text = out.map((l) => (l === "" || l.startsWith(";") ? l : `N${++n} ${l}`)).join("\n");
  } else text = out.join("\n");
  return {
    text, timeS: mp.timeS, filamentMm: mp.filamentMm, filamentCm3: mp.filamentCm3, grams: mp.grams, cost: mp.cost, layers: nLayers,
    byFeature: mp.byFeature,
  };
}
