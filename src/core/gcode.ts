// Deterministic G-code emitter with per-firmware start/end blocks.
import type { Layer } from "./types.ts";
import type { PrintProfiles } from "./profiles.ts";

const fmt = (v: number, d: number) => { const s = v.toFixed(d); return s.includes(".") ? s.replace(/0+$/, "").replace(/\.$/, "") : s; };

export function emitGcode(layers: Layer[], p: PrintProfiles, header: string[] = []): string {
  const { machine, filament, process } = p, out: string[] = [];
  out.push("; generated by Nexspiro", `; machine: ${machine.name} (${machine.firmware})`, `; filament: ${filament.name}`,
    `; process: ${process.name}`, ...header);
  out.push(...startBlock(p));
  out.push("G90", "M83 ; relative extrusion");
  let filamentUsed = 0;
  for (const layer of layers) {
    out.push(`;LAYER:${layer.index}`, `;Z:${fmt(layer.z, 3)}`);
    if (machine.firmware === "bambu") out.push("M73 L" + (layer.index + 1));
    for (const path of layer.paths) {
      out.push(`;TYPE:${path.feature}`);
      const s = path.points[0];
      out.push(`G1 Z${fmt(s.z, 3)} F${fmt(machine.maxSpeed.z * 60, 0)}`);
      out.push(`G0 X${fmt(s.x, 3)} Y${fmt(s.y, 3)} F${fmt(process.travelSpeed * 60, 0)}`);
      let lastF = -1, lastZ = s.z;
      for (let i = 1; i < path.points.length; i++) {
        const q = path.points[i];
        let line = `G1 X${fmt(q.x, 3)} Y${fmt(q.y, 3)}`;
        if (Math.abs(q.z - lastZ) > 1e-4) { line += ` Z${fmt(q.z, 3)}`; lastZ = q.z; }
        line += ` E${fmt(q.e, 5)}`;
        const f = Math.round(q.f * 60);
        if (f !== lastF) { line += ` F${f}`; lastF = f; }
        out.push(line); filamentUsed += q.e;
      }
    }
  }
  out.push(...endBlock(p), `; filament used [mm] = ${fmt(filamentUsed, 2)}`);
  return out.join("\n") + "\n";
}

function startBlock({ machine, filament, process }: PrintProfiles): string[] {
  const t = filament.nozzleTemp, b = filament.bedTemp;
  switch (machine.firmware) {
    case "klipper": return [`PRINT_START EXTRUDER=${t} BED=${b} LAYER_HEIGHT=${process.layerHeight}`];
    case "bambu": return ["M412 S1", `M140 S${b}`, `M104 S${t}`, "G28", `M190 S${b}`, `M109 S${t}`, "M975 S1 ; vibration suppression"];
    case "marlin": return [`M140 S${b}`, `M104 S${t}`, "G28", `M190 S${b}`, `M109 S${t}`, "G92 E0"];
  }
}

function endBlock({ machine }: PrintProfiles): string[] {
  switch (machine.firmware) {
    case "klipper": return ["PRINT_END"];
    case "bambu": return ["M400", "M104 S0", "M140 S0", "M106 P1 S0", "G91", "G1 Z5 F600", "G90"];
    case "marlin": return ["M104 S0", "M140 S0", "G91", "G1 Z5 F600", "G90", "M84"];
  }
}
